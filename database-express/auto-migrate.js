/**
 * auto-migrate.js
 * Menjalankan semua file SQL dari folder /migrations/ yang belum pernah dijalankan.
 * Menyimpan riwayat di tabel `_migration_history` agar tidak double-run.
 */

const mysql = require("mysql2/promise");
const fs = require("fs");
const path = require("path");
require("dotenv").config({ path: path.join(__dirname, "../.env") });

const MIGRATIONS_DIR = path.join(__dirname, "../migrations");

// PostgreSQL (driver pg) bila DATABASE_URL berawalan postgres:// atau postgresql://
const PG = /^postgres(ql)?:\/\//.test(process.env.DATABASE_URL || "");
// Kode galat "sudah ada": tabel/indeks, kolom, definisi tabel, objek, skema, indeks
const PG_SUDAH_ADA = ["42P07", "42701", "42P16", "42710", "42P06", "42P17"];

const catatRiwayat = (connection, file) =>
	PG
		? connection.query('INSERT INTO "_migration_history" (filename) VALUES ($1)', [file])
		: connection.query("INSERT INTO `_migration_history` (filename) VALUES (?)", [file]);

async function autoMigrate() {
	let connection;

	try {
		const dbUrl = process.env.DATABASE_URL;
		if (PG) {
			// Buang query string (?schema=public) yang tidak dikenal pg
			const { Client } = require("pg");
			const u = new URL(dbUrl);
			connection = new Client({
				host: u.hostname,
				port: u.port ? parseInt(u.port) : 5432,
				user: decodeURIComponent(u.username),
				password: decodeURIComponent(u.password),
				database: decodeURIComponent(u.pathname.replace(/^\//, "")),
			});
			await connection.connect();
		} else {
		const match = dbUrl.match(/mysql:\/\/([^:]+):([^@]*)@([^:]+):(\d+)\/([^?]+)/);
		if (!match) throw new Error("Invalid DATABASE_URL format");

		const [, user, password, host, port, database] = match;

		connection = await mysql.createConnection({
			host,
			port: parseInt(port),
			user,
			password,
			database,
			multipleStatements: true,
		});
		}

		console.log("✅ Connected to database");

		// Buat tabel tracking jika belum ada
		await connection.query(PG ? `
			CREATE TABLE IF NOT EXISTS "_migration_history" (
				"id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				"filename" VARCHAR(255) NOT NULL UNIQUE,
				"ran_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
			)
		` : `
			CREATE TABLE IF NOT EXISTS \`_migration_history\` (
				\`id\` INT AUTO_INCREMENT PRIMARY KEY,
				\`filename\` VARCHAR(255) NOT NULL UNIQUE,
				\`ran_at\` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
			)
		`);

		// Ambil daftar migration yang sudah dijalankan
		let rows;
		if (PG) {
			rows = (await connection.query('SELECT filename FROM "_migration_history"')).rows;
		} else {
			[rows] = await connection.query(
				"SELECT filename FROM `_migration_history`"
			);
		}
		const alreadyRan = new Set(rows.map((r) => r.filename));

		// Ambil semua file SQL dari folder migrations, urutkan ascending
		const files = fs
			.readdirSync(MIGRATIONS_DIR)
			.filter((f) => f.endsWith(".sql"))
			.sort();

		let ranCount = 0;

		for (const file of files) {
			if (alreadyRan.has(file)) {
				console.log(`⏭️  Skipped (already ran): ${file}`);
				continue;
			}

			const filePath = path.join(MIGRATIONS_DIR, file);
			const sql = fs.readFileSync(filePath, "utf8");

			console.log(`🔄 Running migration: ${file}`);

			try {
				await connection.query(sql);
				await catatRiwayat(connection, file);
				console.log(`✅ Done: ${file}`);
				ranCount++;
			} catch (err) {
				// Duplicate column/index/table errors = already applied manually
				if (PG ? PG_SUDAH_ADA.includes(err.code) : [1060, 1061, 1050, 1068].includes(err.errno)) {
					console.log(`⏭️  Skipped (already applied): ${file} - ${err.message}`);
					await catatRiwayat(connection, file);
					continue;
				}
				console.error(`❌ Failed: ${file}`);
				console.error(err.message);
				// Continue to next migration instead of stopping
				continue;
			}
		}

		if (ranCount === 0) {
			console.log("✅ All migrations already up to date.");
		} else {
			console.log(`✅ Ran ${ranCount} new migration(s).`);
		}
	} catch (error) {
		console.error("❌ Auto-migrate failed:", error.message);
		process.exit(1);
	} finally {
		if (connection) await connection.end();
	}
}

autoMigrate();
