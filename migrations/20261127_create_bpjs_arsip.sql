-- Arsip bulanan data BPJS Ketenagakerjaan RT/RW. Tiap import Excel disimpan
-- per periode (BLTH, 'YYYY-MM'); import ulang periode yang sama hanya mengganti
-- periode itu, periode lain tidak tersentuh. data/rtrwbpjs.json tetap dipakai
-- sebagai cache Persandingan RT/RW, dibangun dari periode terbaru. Idempoten.

CREATE TABLE IF NOT EXISTS "bpjs_periode" (
    "periode"          CHAR(7)       NOT NULL PRIMARY KEY,
    "nama_file"        VARCHAR(255)  NOT NULL,
    "total_baris"      INTEGER       NOT NULL DEFAULT 0,
    "total_desa"       INTEGER       NOT NULL DEFAULT 0,
    "total_upah"       NUMERIC(18,2) NOT NULL DEFAULT 0,
    "imported_by"      BIGINT        NULL,
    "imported_by_name" VARCHAR(255)  NULL,
    "imported_at"      TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP(0)
);

CREATE TABLE IF NOT EXISTS "bpjs_peserta" (
    "id"           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "periode"      CHAR(7)       NOT NULL REFERENCES "bpjs_periode"("periode") ON DELETE CASCADE,
    "baris_excel"  INTEGER       NOT NULL,
    -- NIK, atau KPJ bila NIK kosong, atau nama|desa: pembanding antar bulan.
    "kunci"        VARCHAR(255)  NOT NULL,
    "nik"          VARCHAR(32)   NOT NULL DEFAULT '',
    "id_pegawai"   VARCHAR(64)   NOT NULL DEFAULT '',
    "desa_kode"    VARCHAR(32)   NOT NULL DEFAULT '',
    "kpj"          VARCHAR(32)   NOT NULL DEFAULT '',
    "kode_tk"      VARCHAR(64)   NOT NULL DEFAULT '',
    "nama_lengkap" VARCHAR(255)  NOT NULL DEFAULT '',
    "tgl_lahir"    VARCHAR(32)   NOT NULL DEFAULT '',
    "upah"         NUMERIC(18,2) NOT NULL DEFAULT 0,
    "rapel"        NUMERIC(18,2) NOT NULL DEFAULT 0,
    "blth"         VARCHAR(32)   NOT NULL DEFAULT '',
    "npp"          VARCHAR(64)   NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS "bpjs_peserta_periode_kunci_index" ON "bpjs_peserta"("periode", "kunci");
CREATE INDEX IF NOT EXISTS "bpjs_peserta_periode_desa_index" ON "bpjs_peserta"("periode", "desa_kode");
CREATE INDEX IF NOT EXISTS "bpjs_peserta_nik_index" ON "bpjs_peserta"("nik");
