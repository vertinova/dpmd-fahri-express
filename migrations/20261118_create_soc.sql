-- SOC (Security Operations Center) di Manajemen Server: insiden, bukti, jurnal, kursor.
-- PostgreSQL, idempoten. Tanpa kolom BOOLEAN.

CREATE TABLE IF NOT EXISTS soc_insiden (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode VARCHAR(24) NOT NULL UNIQUE,
  judul VARCHAR(255) NOT NULL,
  kategori VARCHAR(40) NOT NULL,
  severity VARCHAR(10) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'baru',
  kunci VARCHAR(191) NOT NULL,
  ip_address VARCHAR(45) NULL,
  user_id BIGINT NULL,
  jumlah_event INT NOT NULL DEFAULT 0,
  pertama_at TIMESTAMP(0) NOT NULL,
  terakhir_at TIMESTAMP(0) NOT NULL,
  ditangani_at TIMESTAMP(0) NULL,
  selesai_at TIMESTAMP(0) NULL,
  ditutup_oleh VARCHAR(191) NULL,
  catatan_tutup TEXT NULL,
  analisis_ai TEXT NULL,
  analisis_ai_at TIMESTAMP(0) NULL,
  analisis_jumlah_event INT NOT NULL DEFAULT 0,
  dokumentasi TEXT NULL,
  dokumentasi_at TIMESTAMP(0) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_soc_insiden_status ON soc_insiden (status);
CREATE INDEX IF NOT EXISTS idx_soc_insiden_kunci ON soc_insiden (kunci, status);
CREATE INDEX IF NOT EXISTS idx_soc_insiden_terakhir ON soc_insiden (terakhir_at);

CREATE TABLE IF NOT EXISTS soc_insiden_event (
  insiden_id BIGINT NOT NULL REFERENCES soc_insiden(id) ON DELETE CASCADE,
  sumber VARCHAR(20) NOT NULL,
  ref_id BIGINT NOT NULL,
  PRIMARY KEY (insiden_id, sumber, ref_id)
);

CREATE TABLE IF NOT EXISTS soc_insiden_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  insiden_id BIGINT NOT NULL REFERENCES soc_insiden(id) ON DELETE CASCADE,
  at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  oleh VARCHAR(191) NOT NULL,
  jenis VARCHAR(20) NOT NULL,
  isi TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_soc_insiden_log_insiden ON soc_insiden_log (insiden_id, at);

CREATE TABLE IF NOT EXISTS soc_kursor (
  kunci VARCHAR(50) PRIMARY KEY,
  nilai TEXT NOT NULL,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
